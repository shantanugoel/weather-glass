#!/usr/bin/env python3
"""Turn config.toml into firmware/sdkconfig.defaults.local.

One file to edit, one place to validate. ESP-IDF configures from Kconfig, so
rather than ask anyone to keep a TOML file and a Kconfig fragment in step, the
build generates the fragment from the TOML and refuses to continue if the two
disagree.

    .venv/bin/python tools/gen_config.py            # write the fragment
    .venv/bin/python tools/gen_config.py --check     # validate, write nothing
    .venv/bin/python tools/gen_config.py --print     # show the fragment
"""
from __future__ import annotations

import argparse
import os
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TOML = ROOT / "config.toml"
DEFAULT_OUT = ROOT / "firmware" / "sdkconfig.defaults.local"
DEFAULT_SDKCONFIG = ROOT / "firmware" / "sdkconfig"

# key -> (toml path, kconfig name, type, validator)
def _range(lo: float, hi: float):
    """Numeric bounds that tolerate a quoted "12.9698" as well as 12.9698."""
    def check(v):
        try:
            x = float(v)
        except (TypeError, ValueError):
            return False
        return lo <= x <= hi
    return check


SPEC = [
    (("wifi", "ssid"), "CONFIG_GLASS_WIFI_SSID", str, None),
    (("wifi", "password"), "CONFIG_GLASS_WIFI_PASSWORD", str, None),
    (("location", "latitude"), "CONFIG_GLASS_LATITUDE", str, _range(-90.0, 90.0)),
    (("location", "longitude"), "CONFIG_GLASS_LONGITUDE", str, _range(-180.0, 180.0)),
    (("location", "city"), "CONFIG_GLASS_CITY", str, None),
    (("location", "timezone"), "CONFIG_GLASS_TIMEZONE", str, None),
    (("location", "utc_offset_sec"), "CONFIG_GLASS_UTC_OFFSET_SEC", int,
     _range(-43200, 43200)),
    (("schedule", "day_interval_min"), "CONFIG_GLASS_DAY_INTERVAL_MIN", int,
     _range(1, 1440)),
    (("schedule", "night_interval_min"), "CONFIG_GLASS_NIGHT_INTERVAL_MIN", int,
     _range(1, 1440)),
    (("schedule", "retry_interval_min"), "CONFIG_GLASS_RETRY_INTERVAL_MIN", int,
     _range(1, 1440)),
]


PLACEHOLDERS = {"your-ssid", "your-password"}


def load(toml_path: Path) -> dict:
    if not toml_path.exists():
        sys.exit(
            f"{toml_path.name} not found.\n"
            f"  cp {ROOT / 'config.example.toml'} {toml_path}   then fill it in.")
    with toml_path.open("rb") as fh:
        try:
            return tomllib.load(fh)
        except tomllib.TOMLDecodeError as exc:
            sys.exit(f"{toml_path}: invalid TOML: {exc}")


def render(cfg: dict) -> tuple[str, list[str]]:
    lines = [
        "# Generated by tools/gen_config.py from config.toml - do not edit.",
        "# Edit config.toml instead; this file is regenerated by the build.",
        "",
    ]
    problems: list[str] = []
    for toml_key, kconfig, kind, validate in SPEC:
        section, name = toml_key
        if section not in cfg:
            problems.append(f"[{section}] is missing")
            continue
        if name not in cfg[section]:
            problems.append(f"[{section}] has no '{name}'")
            continue
        value = cfg[section][name]
        if kind is int and not isinstance(value, int):
            problems.append(f"{section}.{name} must be an integer, got {value!r}")
            continue
        if kind is str and not isinstance(value, (str, int, float)):
            problems.append(f"{section}.{name} must be a string or number, got {value!r}")
            continue
        # Kconfig string options take "12.9698", TOML gives a float. Accept
        # either; %g keeps 12.9698 from becoming 12.969800000000001.
        if kind is str and isinstance(value, (int, float)):
            value = f"{value:g}" if isinstance(value, float) else str(value)
        if isinstance(value, str) and value in PLACEHOLDERS:
            problems.append(f"{section}.{name} is still the example value "
                            f"{value!r}; edit config.toml")
            continue
        if validate is not None and not validate(value):
            problems.append(f"{section}.{name} = {value!r} is out of range")
            continue
        if kind is int:
            lines.append(f"{kconfig}={value}")
        else:
            # Escape like a shell so a quote in a passphrase cannot break the
            # fragment or smuggle in another assignment.
            escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{kconfig}="{escaped}"')
    return "\n".join(lines) + "\n", problems


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--toml", type=Path, default=DEFAULT_TOML)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="validate only")
    ap.add_argument("--print", action="store_true", dest="print_only")
    ap.add_argument("--sdkconfig", type=Path, default=DEFAULT_SDKCONFIG,
                    help="generated sdkconfig to invalidate when the fragment changes")
    a = ap.parse_args()

    cfg = load(a.toml)
    # Same escape hatch the other ESP projects here use, so a one-off bench
    # test does not need the file edited.
    for section, name in (("wifi", "ssid"), ("wifi", "password")):
        override = os.environ.get(f"GLASS_{name.upper()}")
        if override is not None:
            cfg.setdefault(section, {})[name] = override

    text, problems = render(cfg)
    if problems:
        sys.exit(f"{a.toml}:\n  " + "\n  ".join(dict.fromkeys(problems)))

    if a.print_only:
        sys.stdout.write(text)
        return
    if a.check:
        print(f"{a.toml.name}: ok ({text.count(chr(10)) - 3} settings)")
        return

    # Only rewrite when something changed, so the build does not look dirty
    # every time CMake re-runs.
    if a.out.exists() and a.out.read_text() == text:
        print(f"{a.out.relative_to(ROOT)}: up to date")
        return
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text)
    print(f"{a.out.relative_to(ROOT)}: written from {a.toml.name}")
    invalidate_sdkconfig(a.sdkconfig)


def invalidate_sdkconfig(path: Path) -> None:
    """Drop a generated sdkconfig so the new fragment actually reaches the build.

    Kconfig applies sdkconfig.defaults* only to symbols that are *absent* from
    firmware/sdkconfig, so editing config.toml alone never changes anything a
    previous build already settled: a bench-test day_interval_min of 1 kept
    winning against a config.toml that said 20, and the panel refreshed once a
    minute while the TOML looked correct. sdkconfig is generated and gitignored
    (everything worth configuring lives in config.toml), so the honest fix for
    a changed fragment is to delete it and let the next configure reseed it.
    """
    for stale in (path, path.with_name(path.name + ".old")):
        if stale.exists():
            stale.unlink()
            try:
                shown = stale.relative_to(ROOT)
            except ValueError:
                shown = stale
            print(f"{shown}: removed, Kconfig will reseed it from the fragment")


if __name__ == "__main__":
    main()
