#!/usr/bin/env python3
"""Bake the photographic glass plates into a 4bpp C array.

    .venv/bin/python tools/gen_plates.py [--preview]

The "liquid glass" in this design is not computed. Upstream ships eleven
photographic plates - sky plus three frosted slabs with their rim lighting,
refraction and drop shadows already in the image - and overlays only text,
icons and dividers. Their own README says not to add procedural bevels or white
fill on top, and that is the rule we follow here too: the firmware picks a
plate and paints data on it.

Plates are stored 4bpp, two pixels per byte, low nibble first, with nibble n
meaning grey level n * 17. At 400x300 that is 60 KB per plate, which lives in
the app image as read-only flash and is expanded into the canvas on demand.

Plates come from vendor/zectrix-weather-glass/glass-plates (MIT, see
docs/ATTRIBUTION.md). Drop a PNG of the same name in assets/glass-plates/ to
override one of them with our own art without touching this script.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor" / "zectrix-weather-glass" / "glass-plates"
LOCAL = ROOT / "assets" / "glass-plates"
OUT = ROOT / "firmware" / "components" / "glass_gfx" / "generated"
PREVIEW = ROOT / "sim" / "out" / "plates"

W, H = 400, 300

# The scenes the compositor asks for, and the plate each one resolves to.
# Mirrors upstream render.py: night variants exist for every scene except
# clear (which becomes the dedicated night plate) and thunder.
SCENES = [
    ("clear", "clear", "night"),
    ("cloud", "cloud", "cloud-night"),
    ("rain", "rain", "rain-night"),
    ("snow", "snow", "snow-night"),
    ("thunder", "thunder", "thunder"),
    ("fog", "fog", "fog-night"),
]


def plate_path(name: str) -> Path:
    """Our own plate wins, so art can be swapped in without a code change."""
    for base in (LOCAL, VENDOR):
        candidate = base / f"{name}.png"
        if candidate.exists():
            return candidate
    raise SystemExit(f"no plate named {name!r} in {LOCAL} or {VENDOR}")


def load_gray(name: str) -> Image.Image:
    """A plate as 400x300 8-bit grey, exactly as upstream loads it.

    Upstream LANCZOS-resizes the 1448x1086 originals into the card; doing the
    same keeps the rims crisp instead of ringing or stair-stepping.
    """
    return Image.open(plate_path(name)).convert("L").resize((W, H), Image.LANCZOS)


def to_4bpp(im: Image.Image) -> bytes:
    """Pack 8-bit grey into 16 levels, two pixels per byte, low nibble first.

    Rounding rather than truncating matters: the panel's 16 levels are the only
    tones it can show, and a systematic half-step down darkens every sky.
    """
    px = list(im.tobytes())
    levels = [(v * 15 + 127) // 255 for v in px]
    out = bytearray(len(levels) // 2)
    for i in range(0, len(levels), 2):
        out[i // 2] = levels[i] | (levels[i + 1] << 4)
    return bytes(out)


def stretch_tonal_range(im: Image.Image) -> Image.Image:
    """Push the plate's tonal range onto the panel's usable span.

    The photographic plates sit between roughly 145 and 245, so on a panel that
    can only show 16 levels the whole image lands in the top three steps and
    reads as blank paper - which is exactly the complaint about the first
    device render. Stretching 5th-95th percentile to 8-248 keeps the highlight
    structure while putting real ink back into the sky and the slab shadows.
    """
    px = list(im.tobytes())
    ordered = sorted(px)
    lo = ordered[int(len(ordered) * 0.05)]
    hi = ordered[int(len(ordered) * 0.95)]
    if hi - lo < 24:
        return im
    span = hi - lo
    return im.point([max(0, min(255, round((v - lo) * 240 / span + 8))) for v in range(256)])


def emit_cc(entries: list[tuple[str, bytes]]) -> str:
    lines = [
        "// Generated by tools/gen_plates.py - do not edit.",
        "// Photographic glass plates, 4bpp, 2 pixels per byte (low nibble first).",
        "",
        '#include "glass_plates.h"',
        "",
        "namespace {",
        "",
    ]
    for name, data in entries:
        sym = f"k_plate_{name.replace('-', '_')}"
        lines.append(f"const uint8_t {sym}[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const glass_plate_t glass_plates[] = {")
    for name, data in entries:
        sym = f"k_plate_{name.replace('-', '_')}"
        lines.append(f'    {{"{name}", {sym}, {len(data)}}},')
    lines.append("};")
    lines.append(f"const size_t glass_plate_count = {len(entries)};")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true", help="also write PNGs to sim/out/plates")
    a = ap.parse_args()

    entries: list[tuple[str, bytes]] = []
    seen: set[str] = set()
    wanted: list[str] = []
    for _, day_plate, night_plate in SCENES:
        for plate in (day_plate, night_plate):
            if plate not in seen:
                seen.add(plate)
                wanted.append(plate)

    if a.preview:
        PREVIEW.mkdir(parents=True, exist_ok=True)
    for plate in wanted:
        im = stretch_tonal_range(load_gray(plate))
        if a.preview:
            im.save(PREVIEW / f"{plate}.png")
            im.quantize(16, method=Image.MEDIANCUT).save(PREVIEW / f"{plate}_16lvl.png")
        entries.append((plate, to_4bpp(im)))

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "glass_plates.cc").write_text(emit_cc(entries))
    print(f"baked {len(entries)} plates "
          f"({sum(len(d) for _, d in entries) / 1024:.0f} KiB of flash)")


if __name__ == "__main__":
    main()
